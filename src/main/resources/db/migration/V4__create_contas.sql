CREATE TABLE contas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(200) NOT NULL,
    valor NUMERIC(19, 2) NOT NULL CHECK (valor > 0),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('PAGAR', 'RECEBER')),
    categoria VARCHAR(100) NOT NULL,
    vencimento DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDENTE', 'PAGA', 'CANCELADA')),
    data_pagamento DATE,
    recorrencia VARCHAR(20) NOT NULL CHECK (recorrencia IN ('UNICA', 'SEMANAL', 'MENSAL', 'ANUAL')),
    observacao VARCHAR(1000),
    parceiro_id BIGINT NOT NULL REFERENCES parceiros (id),
    lancamento_id BIGINT UNIQUE REFERENCES lancamentos (id) ON DELETE SET NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_conta_pagamento CHECK (
        (status = 'PAGA' AND data_pagamento IS NOT NULL)
        OR (status <> 'PAGA' AND data_pagamento IS NULL)
    )
);

CREATE INDEX idx_contas_vencimento ON contas (vencimento);
CREATE INDEX idx_contas_tipo_status ON contas (tipo, status);
CREATE INDEX idx_contas_parceiro ON contas (parceiro_id);
